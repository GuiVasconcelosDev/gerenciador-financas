package br.com.guilhermedev.financas.service;

import br.com.guilhermedev.financas.model.TipoTransacao;
import br.com.guilhermedev.financas.model.Transacao;

import java.sql.*;
import java.time.LocalDate;
import java.util.ArrayList;
import java.util.List;

public class GerenciadorBanco {

    public void inicializarBanco() {
        String sql = """
                CREATE TABLE IF NOT EXISTS transacoes (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    data DATE NOT NULL,
                    descricao TEXT NOT NULL,
                    tipo VARCHAR(20) NOT NULL CHECK (tipo IN ('RECEITA', 'DESPESA')),
                    valor DOUBLE PRECISION NOT NULL
                )
                """;

        try (Connection conn = ConnectionFactory.getConnection();
             Statement stmt = conn.createStatement()) {
            stmt.execute(sql);
        } catch (SQLException e) {
            throw new IllegalStateException("Não foi possível criar ou verificar a tabela transacoes.", e);
        }
    }

    public void salvarTransacao(Transacao transacao) {
        String sql = "INSERT INTO transacoes (data, descricao, tipo, valor) VALUES (?, ?, ?, ?)";

        try (Connection conn = ConnectionFactory.getConnection();
             PreparedStatement stmt = conn.prepareStatement(sql)) {

            stmt.setDate(1, Date.valueOf(transacao.data()));
            stmt.setString(2, transacao.descricao());
            stmt.setString(3, transacao.tipo().name());
            stmt.setDouble(4, transacao.valor());

            stmt.executeUpdate();
            System.out.println("Sua movimentação foi salva com sucesso no Banco de Dados (PostgreSQL)!");

        } catch (SQLException e) {
            throw new IllegalStateException("Não foi possível salvar a transação no banco de dados.", e);
        }
    }


    public List<Transacao> listarTransacoes() {
        List<Transacao> transacoes = new ArrayList<>();
        String sql = "SELECT data, descricao, tipo, valor FROM transacoes ORDER BY data ASC";

        try (Connection conn = ConnectionFactory.getConnection();
             PreparedStatement stmt = conn.prepareStatement(sql);
             ResultSet rs = stmt.executeQuery()) {

            while (rs.next()) {
                LocalDate data = rs.getDate("data").toLocalDate();
                String descricao = rs.getString("descricao");
                TipoTransacao tipo = TipoTransacao.valueOf(rs.getString("tipo"));
                double valor = rs.getDouble("valor");

                transacoes.add(new Transacao(data, descricao, tipo, valor));
            }

        } catch (SQLException e) {
            throw new IllegalStateException("Não foi possível listar as transações do banco de dados.", e);
        }

        return transacoes;
    }

}